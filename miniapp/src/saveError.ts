import { ApiError } from "./api";

/**
 * Один текст ошибки на все формы.
 *
 * 401 здесь — почти всегда не «чужой», а устаревшая сессия: окно жизни initData
 * для записи короче, чем для чтения, поэтому давно открытый миниапп читает
 * нормально, а сохранить уже не может. Говорить «не удалось сохранить» в этом
 * случае вредно — человек будет жать кнопку снова и снова.
 */
export function saveError(e: unknown): string {
  if (e instanceof ApiError) {
    if (e.status === 401) return "Сессия устарела. Закрой планер и открой заново — всё введённое сохранится в поле.";
    if (e.status === 403) return "Нет доступа. Напиши боту /start.";
    if (e.status === 400) return "Проверь поля — что-то не подходит.";
    if (e.status === 429) return "Слишком часто. Подожди немного и попробуй снова.";
    if (e.status >= 500) return "Сервер не отвечает. Попробуй ещё раз через минуту.";
  }
  return "Не удалось сохранить. Попробуй ещё раз.";
}
